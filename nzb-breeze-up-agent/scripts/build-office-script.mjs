// Bundles src/core.ts + src/office/main.ts into one Office Script file that
// can be pasted into Excel (Automate > New Script) or saved as an .osts.
//   npm run build:office  ->  dist-office/NZB_Breeze_Up_Agent.ts
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const core = readFileSync("src/core.ts", "utf8")
  // Office Scripts are a single file: no import/export keywords.
  .replace(/^export (?=(function|interface|type|const) )/gm, "");
const main = readFileSync("src/office/main.ts", "utf8");
const banner = `// NZB Breeze Up Agent - Office Script (generated by scripts/build-office-script.mjs - do not edit by hand)\n// Source: nzb-breeze-up-agent/src/core.ts + src/office/main.ts\n\n`;
mkdirSync("dist-office", { recursive: true });
writeFileSync("dist-office/NZB_Breeze_Up_Agent.ts", banner + main + "\n" + core);
console.log("Wrote dist-office/NZB_Breeze_Up_Agent.ts");
